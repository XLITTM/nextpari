import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { ownerFootballLogo } from '../../server/sports/catalog/ownerFootballMedia.js';
import { approvedFootballLogo, sportsRegion, verifiedPublishedLogo } from './sportsRegion.js';

describe('approved football media', () => {
  it('publishes only the three reviewed provider ids', () => {
    assert.equal(ownerFootballLogo('competition', '94')?.canonicalId, 'football:eng:premier-league');
    assert.equal(ownerFootballLogo('participant', '17230')?.path, '/images/sports/football/arsenal.png');
    assert.equal(ownerFootballLogo('participant', '708')?.path, '/images/sports/football/manchester-city.png');
    assert.equal(ownerFootballLogo('competition', null), null);
    assert.equal(ownerFootballLogo('participant', '17230')?.canonicalId === ownerFootballLogo('participant', '708')?.canonicalId, false);
  });

  it('does not assign a badge from a similar name or the other Bundesliga', () => {
    assert.equal(ownerFootballLogo('competition', 'Austria Bundesliga'), null);
    assert.equal(ownerFootballLogo('competition', 'Germany Bundesliga'), null);
    assert.equal(approvedFootballLogo('/crest1.webp'), null);
    assert.equal(approvedFootballLogo('https://football-logos.cc/badge.png'), null);
    assert.equal(approvedFootballLogo('/images/sports/football/arsenal.png'), '/images/sports/football/arsenal.png');
    assert.equal(verifiedPublishedLogo('team', 'Manchester City'), '/images/sports/football/manchester-city.png');
    assert.equal(verifiedPublishedLogo('team', 'Manchester United'), '/images/sports/football/manchester-united.png');
    assert.equal(verifiedPublishedLogo('team', 'Манчестер Юнайтед'), '/images/sports/football/manchester-united.png');
    assert.equal(verifiedPublishedLogo('competition', 'Premier League', 'Lebanon'), null);
    assert.equal(verifiedPublishedLogo('competition', 'Premier League', 'England'), '/images/sports/football/premier-league.png');
    assert.equal(verifiedPublishedLogo('competition', 'Bundesliga', 'Germany'), '/images/sports/football/bundesliga.png');
    assert.equal(verifiedPublishedLogo('competition', 'Bundesliga', 'Austria'), null);
    assert.equal(verifiedPublishedLogo('competition', 'Ligue 1', 'France'), '/images/sports/football/ligue-1.png');
    assert.equal(verifiedPublishedLogo('competition', 'Ligue 1', 'Senegal'), null);
    assert.equal(verifiedPublishedLogo('competition', 'LaLiga', 'Spain'), '/images/sports/football/la-liga.png');
    assert.equal(verifiedPublishedLogo('competition', 'Championship', 'South Africa'), null);
    assert.equal(verifiedPublishedLogo('team', 'Real Madrid', 'Spain', 'LaLiga'), '/images/sports/football/real-madrid.png');
    assert.equal(verifiedPublishedLogo('team', 'FK Zenit Saint Petersburg', 'Russia', 'Premier League'), '/images/sports/football/zenit.png');
    assert.equal(verifiedPublishedLogo('team', 'CSKA Moscow', 'Russia', 'Premier League'), '/images/sports/football/cska-moskva.png');
    assert.equal(verifiedPublishedLogo('team', 'Fenerbahce Istanbul', 'Turkiye', 'Super Lig'), '/images/sports/football/fenerbahce.png');
    assert.equal(verifiedPublishedLogo('team', 'Racing Club De Lens', 'France', 'Ligue 1'), '/images/sports/football/rc-lens.png');
    assert.equal(verifiedPublishedLogo('team', 'TSG Hoffenheim', 'Germany', 'Bundesliga'), '/images/sports/football/hoffenheim.png');
    assert.equal(verifiedPublishedLogo('team', 'Celtic Glasgow', 'Scotland', 'Premiership'), '/images/sports/football/celtic.png');
    assert.equal(verifiedPublishedLogo('team', 'Bolton Wanderers', 'England', 'Championship'), '/images/sports/football/bolton.png');
    assert.equal(verifiedPublishedLogo('team', 'AFC Bournemouth', 'England', 'Premier League'), '/images/sports/football/bournemouth.png');
    assert.equal(verifiedPublishedLogo('team', 'Royal Charleroi SC', 'Belgium', 'Pro League'), '/images/sports/football/charleroi.png');
    assert.equal(verifiedPublishedLogo('team', 'St. Truidense VV', 'Belgium', 'Pro League'), '/images/sports/football/sint-truidense.png');
    assert.equal(verifiedPublishedLogo('team', 'RSC Anderlecht Futures', 'Belgium', 'Challenger Pro League'), null);
    assert.equal(verifiedPublishedLogo('team', 'Arsenal Women', 'England', 'Women Super League'), null);
    assert.equal(verifiedPublishedLogo('team', 'FC Nantes', 'France', 'Premiere Ligue, Women'), null);
    assert.equal(verifiedPublishedLogo('team', 'Goias EC GO', 'Brazil', 'U20 Copa Goias, 1. Divisao'), null);
    assert.equal(verifiedPublishedLogo('team', 'Barcelona SC', 'Ecuador', 'Liga Pro'), null);
    assert.equal(verifiedPublishedLogo('team', 'FC Rangers', 'Andorra', 'Premier League'), null);
    assert.equal(verifiedPublishedLogo('team', 'Rangers', 'Scotland', 'Premiership'), '/images/sports/football/rangers.png');
    assert.equal(verifiedPublishedLogo('team', 'Hannover 96 II', 'Germany', 'Regionalliga'), null);
    assert.equal(verifiedPublishedLogo('team', 'SSC Napoli', 'Italy', 'Serie A'), '/images/sports/football/napoli.png');
    assert.equal(verifiedPublishedLogo('team', 'Lille OSC', 'France', 'Ligue 1'), '/images/sports/football/lille.png');
    assert.equal(verifiedPublishedLogo('team', 'Olympique Lyon', 'France', 'Ligue 1'), '/images/sports/football/lyon.png');
    assert.equal(verifiedPublishedLogo('team', 'Strasbourg Alsace', 'France', 'Ligue 1'), '/images/sports/football/rc-strasbourg-alsace.png');
    assert.equal(verifiedPublishedLogo('team', 'Stade Brest 29', 'France', 'Ligue 1'), '/images/sports/football/brest.png');
    assert.equal(verifiedPublishedLogo('team', 'RC Celta de Vigo', 'Spain', 'LaLiga'), '/images/sports/football/celta.png');
    assert.equal(verifiedPublishedLogo('team', 'Torino FC', 'Italy', 'Serie A'), '/images/sports/football/torino.png');
    assert.equal(verifiedPublishedLogo('team', 'Toulouse FC', 'France', 'Ligue 1'), '/images/sports/football/toulouse.png');
    assert.equal(verifiedPublishedLogo('team', 'AS Monaco', 'France', 'Ligue 1'), '/images/sports/football/as-monaco.png');
    assert.equal(verifiedPublishedLogo('team', 'AJ Auxerre', 'France', 'Ligue 1'), '/images/sports/football/auxerre.png');
    assert.equal(verifiedPublishedLogo('team', 'Juventus Turin', 'Italy', 'Serie A'), '/images/sports/football/juventus.png');
    assert.equal(verifiedPublishedLogo('team', 'Venezia FC', 'Italy', 'Serie A'), '/images/sports/football/venezia.png');
    assert.equal(verifiedPublishedLogo('team', 'Angers SCO', 'France', 'Ligue 1'), '/images/sports/football/angers.png');
    assert.equal(verifiedPublishedLogo('team', 'Lazio Rome', 'Italy', 'Serie A'), '/images/sports/football/lazio.png');
    assert.equal(verifiedPublishedLogo('team', 'Olympique Lyon Women', 'France', 'Premiere Ligue, Women'), null);
  });

  it('shows home-nation flags and leaves international codes blank', () => {
    assert.match(sportsRegion('at'), /Австрия/);
    assert.match(sportsRegion('de'), /Германия/);
    assert.notEqual(sportsRegion('at'), sportsRegion('de'));
    assert.match(sportsRegion('eng'), /Англия/);
    assert.match(sportsRegion('sco'), /Шотландия/);
    assert.match(sportsRegion('wal'), /Уэльс/);
    assert.match(sportsRegion('nir'), /Северная Ирландия/);
    assert.equal(sportsRegion('eu'), '');
    assert.equal(sportsRegion(''), '');
    assert.equal(sportsRegion('unknown'), '');
  });
});
